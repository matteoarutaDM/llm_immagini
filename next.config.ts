import type { NextConfig } from "next";

// Baseline CSP: this app keeps the auth token in localStorage and calls only
// same-origin API routes, so a same-origin-only policy blocks third-party
// script/style/frame injection without breaking the app. 'unsafe-inline' /
// 'unsafe-eval' are kept for Next.js dev-mode (fast refresh, inline styles
// from Tailwind); tighten further if this is deployed to production.
const contentSecurityPolicy = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline' 'unsafe-eval'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "connect-src 'self'",
  "font-src 'self' data:",
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
].join("; ");

const nextConfig: NextConfig = {
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "Content-Security-Policy", value: contentSecurityPolicy },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "X-Frame-Options", value: "DENY" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
        ],
      },
    ];
  },
};

export default nextConfig;
